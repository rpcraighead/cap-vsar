@dataclass
class DiagnosticFinding:
    """Individual rule finding or anomaly report."""

    rule_id: str
    category: str  # e.g. "BEARING_GEOMETRY", "COVERAGE_406", "CONE_OF_CONFUSION", "RADIO_HYGIENE"
    status: str  # "PASS", "INFO", "WARNING", "FAIL"
    title: str
    message: str
    details: Dict[str, Any]


@dataclass
class DiagnosticReport:
    """Comprehensive post-flight diagnostic evaluation report."""

    session_id: str
    generated_at: str
    total_frames: int
    duration_seconds: float
    summary_status: str  # "PASS", "WARNING", "FAIL"
    pass_count: int
    warn_count: int
    fail_count: int
    info_count: int
    findings: List[DiagnosticFinding]
    metrics: Dict[str, Any]

    def to_dict(self) -> Dict[str, Any]:
        return {
            "session_id": self.session_id,
            "generated_at": self.generated_at,
            "total_frames": self.total_frames,
            "duration_seconds": round(self.duration_seconds, 1),
            "summary_status": self.summary_status,
            "scorecard": {
                "pass": self.pass_count,
                "warn": self.warn_count,
                "fail": self.fail_count,
                "info": self.info_count,
            },
            "metrics": self.metrics,
            "findings": [asdict(f) for f in self.findings],
        }

    def to_markdown(self) -> str:
        """Generate human-readable Markdown debrief report."""
        status_emoji = "🟢 PASS" if self.summary_status == "PASS" else ("🟡 WARNING" if self.summary_status == "WARNING" else "🔴 FAIL")
        lines = [
            f"# CAP V-SAR Flight Diagnostic Report — {self.session_id}",
            f"> **Generated**: {self.generated_at} | **Duration**: {self.duration_seconds:.1f}s | **Frames**: {self.total_frames}",
            f"> **Overall Assessment**: **{status_emoji}** ({self.pass_count} Pass, {self.warn_count} Warn, {self.fail_count} Fail, {self.info_count} Info)",
            "",
            "---",
            "",
            "## 1. Executive Summary & Telemetry Metrics",
            "",
            "| Metric | Value | Reference / Standard |",
            "|---|---|---|",
        ]
        for k, v in self.metrics.items():
            lines.append(f"| `{k}` | **{v}** | Operational Baseline |")

        lines.extend([
            "",
            "---",
            "",
            "## 2. Automated Rule Evaluation Scorecard",
            "",
        ])

        for idx, f in enumerate(self.findings, 1):
            badge = {
                "PASS": "✅ PASS",
                "INFO": "ℹ️ INFO",
                "WARNING": "⚠️ WARN",
                "FAIL": "❌ FAIL",
            }.get(f.status, f.status)
            lines.append(f"### {idx}. [{badge}] {f.title} (`{f.rule_id}`)")
            lines.append(f"**Category**: `{f.category}`")
            lines.append("")
            lines.append(f"{f.message}")
            if f.details:
                lines.append("")
                lines.append("```json")
                lines.append(json.dumps(f.details, indent=2))
                lines.append("```")
            lines.append("")

        lines.extend([
            "---",
            "*Report generated by CAP V-SAR AI Mission Pilot Post-Flight Test Engine.*",
            "",
        ])
        return "\n".join(lines)


