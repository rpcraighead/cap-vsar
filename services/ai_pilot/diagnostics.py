    def _eval_bearing_geometry(self, frames: List[Dict[str, Any]]) -> Tuple[List[DiagnosticFinding], Dict[str, Any]]:
        """Rule 1: Evaluate true and relative bearing precision against spherical trigonometry."""
        findings: List[DiagnosticFinding] = []
        metrics: Dict[str, Any] = {}

        valid_frames = [f for f in frames if f.get("df_valid") == 1 and f.get("scenario_active") == 1 and not f.get("df_in_cone")]
        if not valid_frames:
            findings.append(
                DiagnosticFinding(
                    rule_id="DF_GEOM_01",
                    category="BEARING_GEOMETRY",
                    status="INFO",
                    title="No Active In-Range DF Reception Logged",
                    message="No frames with valid non-cone DF bearings were logged during the flight window.",
                    details={"valid_frames": 0},
                )
            )
            return findings, metrics

        errors: List[float] = []
        spreads: List[float] = []
        for f in valid_frames:
            ac_lat, ac_lon = f.get("lat", 0.0), f.get("lon", 0.0)
            bc_lat, bc_lon = f.get("beacon_lat", 0.0), f.get("beacon_lon", 0.0)
            true_geom = calc_great_circle_bearing_deg(ac_lat, ac_lon, bc_lat, bc_lon)

            # Check logged bearing_true
            logged_true = f.get("df_bearing_true", 0.0)
            err = calc_angle_difference_deg(logged_true, true_geom)
            errors.append(err)
            spreads.append(f.get("df_spread_deg", 0.0))

        rms_error = math.sqrt(sum(e * e for e in errors) / len(errors))
        max_error = max(errors)
        mean_spread = sum(spreads) / len(spreads) if spreads else 0.0

        metrics["bearing_rms_error_deg"] = round(rms_error, 2)
        metrics["bearing_max_error_deg"] = round(max_error, 2)
        metrics["bearing_mean_spread_deg"] = round(mean_spread, 2)
        metrics["valid_bearing_samples"] = len(valid_frames)

        if rms_error <= 6.0:
            findings.append(
                DiagnosticFinding(
                    rule_id="DF_GEOM_01",
                    category="BEARING_GEOMETRY",
                    status="PASS",
                    title="DF Bearing Geometry Verified Within Standards",
                    message=f"Root-Mean-Square bearing error was {rms_error:.2f}° (max {max_error:.2f}°), within the 6.0° operational tolerance.",
                    details={"rms_error": round(rms_error, 2), "max_error": round(max_error, 2), "samples": len(errors)},
                )
            )
        elif rms_error <= 15.0:
            findings.append(
                DiagnosticFinding(
                    rule_id="DF_GEOM_01",
                    category="BEARING_GEOMETRY",
                    status="WARNING",
                    title="Elevated Bearing Discrepancy Detected",
                    message=f"RMS bearing error was {rms_error:.2f}° (max {max_error:.2f}°). May indicate banking drag error, multipath reflections, or terrain masking.",
                    details={"rms_error": round(rms_error, 2), "max_error": round(max_error, 2)},
                )
            )
        else:
            findings.append(
                DiagnosticFinding(
                    rule_id="DF_GEOM_01",
                    category="BEARING_GEOMETRY",
                    status="FAIL",
                    title="Severe Bearing Deviation / Mounting Misalignment",
                    message=f"RMS bearing error exceeded limits at {rms_error:.2f}° (max {max_error:.2f}°). Check if TOP/BOTTOM antenna mounting was reversed or calibration offset was incorrect.",
                    details={"rms_error": round(rms_error, 2), "max_error": round(max_error, 2)},
                )
            )

        return findings, metrics

    def _eval_becker_vs_rt600_coverage(self, frames: List[Dict[str, Any]]) -> Tuple[List[DiagnosticFinding], Dict[str, Any]]:
        """Rule 2: Verify authentic 406 coverage divergence between Becker 517 and RT-600."""
        findings: List[DiagnosticFinding] = []
        metrics: Dict[str, Any] = {}

        becker_frames = [f for f in frames if f.get("df_head_type") == 0]
        rt600_frames = [f for f in frames if f.get("df_head_type") == 1]

        metrics["becker_frames"] = len(becker_frames)
        metrics["rt600_frames"] = len(rt600_frames)

        # Inspect frames on 406 MHz band
        band_406_frames = [f for f in frames if 400.0 <= f.get("df_band_mhz", 0.0) <= 410.0]
        if not band_406_frames:
            findings.append(
                DiagnosticFinding(
                    rule_id="DF_COV_406",
                    category="COVERAGE_406",
                    status="INFO",
                    title="No 406 MHz Sortie Segment Logged",
                    message="Flight data recorder did not record active 406 MHz beacon tracking during this session.",
                    details={},
                )
            )
            return findings, metrics

        # Check if beacon was on off-channel 406 (e.g. 406.037 / channel F)
        # Becker emergency mode MUST NOT hear off-channel 406.037
        leaks = 0
        operator_mistakes = 0
        for f in becker_frames:
            # Becker emergency mode (mode 0)
            if f.get("df_mode") == 0 and f.get("df_active_freq_hz") == 406025000:
                # If beacon frequency is defined and != 406.025 MHz
                beacon_hz = f.get("beacon_freq_hz", 0)
                if beacon_hz and abs(beacon_hz - 406025000) > 3000:
                    if f.get("df_valid") == 1 and f.get("df_signal", 0.0) > 0.05:
                        leaks += 1

        if leaks > 0:
            findings.append(
                DiagnosticFinding(
                    rule_id="DF_COV_406_LEAK",
                    category="COVERAGE_406",
                    status="FAIL",
                    title="Simulation Anomaly: Becker Emergency 406 Channel Leak",
                    message=f"Becker SAR-DF-517 in Emergency mode received signal on an off-channel 406 beacon ({leaks} frames). Per manual, Becker Emergency is strictly locked to 406.025 MHz.",
                    details={"leaked_frames": leaks},
                )
            )
        else:
            findings.append(
                DiagnosticFinding(
                    rule_id="DF_COV_406",
                    category="COVERAGE_406",
                    status="PASS",
                    title="Becker 517 / RT-600 406 Channel Selectivity Verified",
                    message="Head channel selectivity and band gating conformed to authentic avionics specifications across 406 MHz monitoring.",
                    details={"406_frames_analyzed": len(band_406_frames)},
                )
            )

        return findings, metrics

    def _eval_cone_of_confusion(self, frames: List[Dict[str, Any]]) -> Tuple[List[DiagnosticFinding], Dict[str, Any]]:
        """Rule 3: Evaluate cone of confusion detection directly over the beacon."""
        findings: List[DiagnosticFinding] = []
        metrics: Dict[str, Any] = {}

        # Look for overhead passage where distance < altitude / tan(60 deg)
        cone_frames = [f for f in frames if f.get("df_in_cone") == 1]
        metrics["cone_passage_frames"] = len(cone_frames)

        if not cone_frames:
            findings.append(
                DiagnosticFinding(
                    rule_id="DF_CONE_01",
                    category="CONE_OF_CONFUSION",
                    status="INFO",
                    title="No Overhead Beacon Passage",
                    message="Aircraft did not penetrate the overhead cone of confusion during this flight log.",
                    details={},
                )
            )
            return findings, metrics

        # Verify that during cone passage, df_valid is 0 (needle suppressed to prevent wild swings)
        invalid_in_cone = sum(1 for f in cone_frames if f.get("df_valid") == 0)
        ratio = invalid_in_cone / len(cone_frames)

        metrics["cone_valid_suppression_ratio"] = round(ratio, 2)
        if ratio >= 0.90:
            findings.append(
                DiagnosticFinding(
                    rule_id="DF_CONE_01",
                    category="CONE_OF_CONFUSION",
                    status="PASS",
                    title="Cone of Confusion Valid Bearing Suppression Verified",
                    message=f"During {len(cone_frames)} frames in the overhead cone, bearing was properly invalidated ({ratio*100:.1f}%), preventing reverse needle whip.",
                    details={"cone_frames": len(cone_frames), "suppression_pct": round(ratio * 100, 1)},
                )
            )
        else:
            findings.append(
                DiagnosticFinding(
                    rule_id="DF_CONE_01",
                    category="CONE_OF_CONFUSION",
                    status="FAIL",
                    title="Erroneous Valid Bearing Inside Cone of Confusion",
                    message=f"Bearing was marked valid in {(1.0-ratio)*100:.1f}% of cone passage frames. Flight crew could be misled by inverted bearings.",
                    details={"cone_frames": len(cone_frames), "valid_leaks": len(cone_frames) - invalid_in_cone},
                )
            )

        return findings, metrics

    def _eval_squelch_and_timehold(self, frames: List[Dict[str, Any]]) -> Tuple[List[DiagnosticFinding], Dict[str, Any]]:
        """Rule 4: Evaluate squelch thresholding and timehold expiration."""
        findings: List[DiagnosticFinding] = []
        metrics: Dict[str, Any] = {}

        # Check if squelch was set excessively high (> 75%) causing deafness
        high_sq_frames = [f for f in frames if f.get("df_squelch", -1.0) > 75.0]
        metrics["high_squelch_frames"] = len(high_sq_frames)

        if high_sq_frames:
            findings.append(
                DiagnosticFinding(
                    rule_id="DF_SQUELCH_01",
                    category="SQUELCH_TIMING",
                    status="WARNING",
                    title="Excessive Squelch Setting Logged",
                    message=f"DF squelch was set above 75% for {len(high_sq_frames)} frames. This may suppress marginal search beacons beyond 10 NM.",
                    details={"high_squelch_frames": len(high_sq_frames)},
                )
            )
        else:
            findings.append(
                DiagnosticFinding(
                    rule_id="DF_SQUELCH_01",
                    category="SQUELCH_TIMING",
                    status="PASS",
                    title="Squelch Configuration Optimal",
                    message="Squelch settings remained within normal operating range (Auto Squelch or <= 60%).",
                    details={},
                )
            )

        return findings, metrics

    def _eval_airframe_shadowing(self, frames: List[Dict[str, Any]]) -> Tuple[List[DiagnosticFinding], Dict[str, Any]]:
        """Rule 5: Evaluate airframe shadowing and banking attenuation."""
        findings: List[DiagnosticFinding] = []
        metrics: Dict[str, Any] = {}

        bank_frames = [f for f in frames if abs(f.get("roll_deg", 0.0)) > 20.0]
        shadowed_frames = [f for f in frames if f.get("df_airframe_shadowed") == 1]

        metrics["steep_turn_frames"] = len(bank_frames)
        metrics["airframe_shadowed_frames"] = len(shadowed_frames)

        if not bank_frames:
            findings.append(
                DiagnosticFinding(
                    rule_id="DF_SHADOW_01",
                    category="AIRFRAME_SHADOWING",
                    status="INFO",
                    title="No Steep Turns Logged",
                    message="Flight maintained shallow bank angles (|roll| <= 20°); airframe shadowing was minimal.",
                    details={},
                )
            )
            return findings, metrics

        if shadowed_frames:
            max_atten = max(f.get("df_airframe_attenuation_db", 0.0) for f in shadowed_frames)
            metrics["max_airframe_attenuation_db"] = round(max_atten, 1)
            findings.append(
                DiagnosticFinding(
                    rule_id="DF_SHADOW_01",
                    category="AIRFRAME_SHADOWING",
                    status="PASS",
                    title="Airframe Wing/Fuselage Shadowing Captured",
                    message=f"Detected {len(shadowed_frames)} frames of airframe shadowing during turns (peak attenuation: {max_atten:.1f} dB). Heading recovery permitted clean re-acquisition.",
                    details={"shadowed_frames": len(shadowed_frames), "peak_atten_db": round(max_atten, 1)},
                )
            )
        else:
            findings.append(
                DiagnosticFinding(
                    rule_id="DF_SHADOW_01",
                    category="AIRFRAME_SHADOWING",
                    status="INFO",
                    title="Turns Logged Without Directional Shadowing",
                    message=f"Logged {len(bank_frames)} banked frames without significant wing nulling.",
                    details={"bank_frames": len(bank_frames)},
                )
            )

        return findings, metrics

    def _eval_cap_radios(self, frames: List[Dict[str, Any]]) -> Tuple[List[DiagnosticFinding], Dict[str, Any]]:
        """Rule 6: Evaluate Technisonic TDFM-136B and Garmin GMA-1347 operating procedures."""
        findings: List[DiagnosticFinding] = []
        metrics: Dict[str, Any] = {}

        # 1. PTT Interlock Check: ptt=True with mic_selected=False MUST NOT transmit
        interlock_violations = 0
        for f in frames:
            if f.get("cap_fm_ptt") and not f.get("cap_fm_mic_selected"):
                if f.get("cap_fm_transmitting"):
                    interlock_violations += 1

        metrics["interlock_violations"] = interlock_violations
        if interlock_violations > 0:
            findings.append(
                DiagnosticFinding(
                    rule_id="RAD_INTLK_01",
                    category="RADIO_HYGIENE",
                    status="FAIL",
                    title="Audio Panel PTT Interlock Failure",
                    message=f"TDFM-136B keyed RF transmission for {interlock_violations} frames while COM3 MIC was unselected on the GMA 1347 audio panel!",
                    details={"violations": interlock_violations},
                )
            )
        else:
            findings.append(
                DiagnosticFinding(
                    rule_id="RAD_INTLK_01",
                    category="RADIO_HYGIENE",
                    status="PASS",
                    title="Audio Panel PTT Interlock Intact",
                    message="PTT keying strictly respected GMA 1347 COM3 MIC selection gating.",
                    details={},
                )
            )

        # 2. Time-Out Timer (TOT) Check: continuous PTT <= 60 seconds
        max_continuous_ptt_s = 0.0
        current_ptt_s = 0.0
        for idx in range(1, len(frames)):
            f_prev = frames[idx - 1]
            f_curr = frames[idx]
            dt = max(0.0, f_curr.get("sim_time_s", 0.0) - f_prev.get("sim_time_s", 0.0))
            if f_curr.get("cap_fm_transmitting"):
                current_ptt_s += dt
                if current_ptt_s > max_continuous_ptt_s:
                    max_continuous_ptt_s = current_ptt_s
            else:
                current_ptt_s = 0.0

        metrics["max_continuous_ptt_seconds"] = round(max_continuous_ptt_s, 1)
        if max_continuous_ptt_s > 60.0:
            findings.append(
                DiagnosticFinding(
                    rule_id="RAD_TOT_01",
                    category="RADIO_HYGIENE",
                    status="WARNING",
                    title="Time-Out Timer (TOT) Warning: Long Continuous Transmission",
                    message=f"Continuous RF transmission was held for {max_continuous_ptt_s:.1f}s, exceeding the standard 60-second CAP FM Time-Out Timer limit.",
                    details={"max_ptt_sec": round(max_continuous_ptt_s, 1)},
                )
            )
        else:
            findings.append(
                DiagnosticFinding(
                    rule_id="RAD_TOT_01",
                    category="RADIO_HYGIENE",
                    status="PASS",
                    title="Transmission Duration Within TOT Limits",
                    message=f"Longest continuous transmission was {max_continuous_ptt_s:.1f}s (limit: 60s).",
                    details={"max_ptt_sec": round(max_continuous_ptt_s, 1)},
                )
            )

        # 3. Guard Receiver Tuning Check: 168.650 MHz
        guard_mismatches = sum(1 for f in frames if f.get("cap_fm_guard_freq_hz") != 168650000 and f.get("cap_fm_power"))
        if guard_mismatches > 0:
            findings.append(
                DiagnosticFinding(
                    rule_id="RAD_GUARD_01",
                    category="RADIO_HYGIENE",
                    status="WARNING",
                    title="Non-Standard Guard Receiver Frequency",
                    message="TDFM-136B dedicated Guard receiver was not tuned to the standard CAP National Guard frequency (168.650 MHz / GD1).",
                    details={"mismatch_frames": guard_mismatches},
                )
            )
        else:
            findings.append(
                DiagnosticFinding(
                    rule_id="RAD_GUARD_01",
                    category="RADIO_HYGIENE",
                    status="PASS",
                    title="Guard Receiver Frequency Compliant (168.650 MHz)",
                    message="Dedicated Guard receiver maintained standard 168.650 MHz listening watch.",
                    details={},
                )
            )

        return findings, metrics

    def _eval_cospas_sarsat_decode(self, frames: List[Dict[str, Any]]) -> Tuple[List[DiagnosticFinding], Dict[str, Any]]:
        """Rule 7: Evaluate COSPAS-SARSAT Hex15 decode integrity and protocol consistency."""
        findings: List[DiagnosticFinding] = []
        metrics: Dict[str, Any] = {}

        sync_frames = [f for f in frames if f.get("cs_sync") == 1]
        metrics["cospas_sarsat_sync_frames"] = len(sync_frames)

        if not sync_frames:
            findings.append(
                DiagnosticFinding(
                    rule_id="CS_DECODE_01",
                    category="COSPAS_SARSAT",
                    status="INFO",
                    title="No Decoded 406 Frames Received",
                    message="No BCH-protected COSPAS-SARSAT digital frames were decoded during this sortie.",
                    details={},
                )
            )
            return findings, metrics

        # Check Hex15 format
        valid_hex15 = True
        sample_hex = ""
        for f in sync_frames:
            hex15 = f.get("cs_hex15", "")
            if hex15:
                sample_hex = hex15
                if len(hex15) != 15 or not all(c in "0123456789ABCDEFabcdef" for c in hex15):
                    valid_hex15 = False
                    break

        if valid_hex15 and sample_hex:
            findings.append(
                DiagnosticFinding(
                    rule_id="CS_DECODE_01",
                    category="COSPAS_SARSAT",
                    status="PASS",
                    title="COSPAS-SARSAT 15-Hex Ident Decoded Validly",
                    message=f"Received valid 15-Hex beacon identifier: {sample_hex.upper()}.",
                    details={"sample_hex15": sample_hex.upper(), "sync_frames": len(sync_frames)},
                )
            )
        elif not valid_hex15:
            findings.append(
                DiagnosticFinding(
                    rule_id="CS_DECODE_01",
                    category="COSPAS_SARSAT",
                    status="FAIL",
                    title="Corrupted 15-Hex Identifier in Decoded Frame",
                    message=f"Decoded identifier failed 15-character hex specification: '{sample_hex}'.",
                    details={"corrupted_hex15": sample_hex},
                )
            )

        return findings, metrics

