# Geodesy & Bearing Math Helpers
# ------------------------------------------------------------------------------

def calc_great_circle_bearing_deg(lat1: float, lon1: float, lat2: float, lon2: float) -> float:
    """Calculate true forward initial bearing from (lat1, lon1) to (lat2, lon2) in degrees [0..360)."""
    phi1 = math.radians(lat1)
    phi2 = math.radians(lat2)
    dlambda = math.radians(lon2 - lon1)

    y = math.sin(dlambda) * math.cos(phi2)
    x = math.cos(phi1) * math.sin(phi2) - math.sin(phi1) * math.cos(phi2) * math.cos(dlambda)
    bearing = math.degrees(math.atan2(y, x))
    return (bearing + 360.0) % 360.0


def calc_angle_difference_deg(deg1: float, deg2: float) -> float:
    """Smallest absolute angle difference between two bearings in degrees [0..180]."""
    diff = abs(deg1 - deg2) % 360.0
    return 360.0 - diff if diff > 180.0 else diff


