class FlightDiagnosticEngine:
    """Evaluates raw flight data records against operational rules."""

    def __init__(self) -> None:
        pass

    def evaluate_frames(self, frames: List[Union[FDRFrame, Dict[str, Any]]], session_id: str = "SESSION") -> DiagnosticReport:
        """Evaluate a list of FDR frames (as FDRFrame objects or dicts)."""
        if not frames:
            return DiagnosticReport(
                session_id=session_id,
                generated_at=datetime.datetime.now(datetime.timezone.utc).isoformat(),
                total_frames=0,
                duration_seconds=0.0,
                summary_status="WARNING",
                pass_count=0,
                warn_count=1,
                fail_count=0,
                info_count=0,
                findings=[
                    DiagnosticFinding(
                        rule_id="EMPTY_LOG",
                        category="DATA_INTEGRITY",
                        status="WARNING",
                        title="Empty Recording Stream",
                        message="No FDR telemetry frames were provided for evaluation.",
                        details={},
                    )
                ],
                metrics={},
            )

        # Normalize to list of dicts
        raw_frames: List[Dict[str, Any]] = [f.to_dict() if isinstance(f, FDRFrame) else f for f in frames]
        duration = 0.0
        if len(raw_frames) >= 2:
            t0 = raw_frames[0].get("sim_time_s", 0.0)
            t1 = raw_frames[-1].get("sim_time_s", 0.0)
            duration = max(0.0, t1 - t0)

        findings: List[DiagnosticFinding] = []
        metrics: Dict[str, Any] = {}

        # 1. Evaluate DF Bearing Geometry & Math Truth
        f_geom, m_geom = self._eval_bearing_geometry(raw_frames)
        findings.extend(f_geom)
        metrics.update(m_geom)

        # 2. Evaluate Becker 517 vs RT-600 406 Coverage
        f_cov, m_cov = self._eval_becker_vs_rt600_coverage(raw_frames)
        findings.extend(f_cov)
        metrics.update(m_cov)

        # 3. Evaluate Cone of Confusion & Overhead Passage
        f_cone, m_cone = self._eval_cone_of_confusion(raw_frames)
        findings.extend(f_cone)
        metrics.update(m_cone)

        # 4. Evaluate Squelch and Timehold Decay
        f_sq, m_sq = self._eval_squelch_and_timehold(raw_frames)
        findings.extend(f_sq)
        metrics.update(m_sq)

        # 5. Evaluate Airframe Shadowing & Banking Masking
        f_shd, m_shd = self._eval_airframe_shadowing(raw_frames)
        findings.extend(f_shd)
        metrics.update(m_shd)

        # 6. Evaluate CAP Radio (TDFM-136B & GMA-1347) Hygiene
        f_rad, m_rad = self._eval_cap_radios(raw_frames)
        findings.extend(f_rad)
        metrics.update(m_rad)

        # 7. Evaluate COSPAS-SARSAT Hex15 Decodes
        f_cs, m_cs = self._eval_cospas_sarsat_decode(raw_frames)
        findings.extend(f_cs)
        metrics.update(m_cs)

        # Tally counts
        pass_count = sum(1 for f in findings if f.status == "PASS")
        warn_count = sum(1 for f in findings if f.status == "WARNING")
        fail_count = sum(1 for f in findings if f.status == "FAIL")
        info_count = sum(1 for f in findings if f.status == "INFO")

        if fail_count > 0:
            summary_status = "FAIL"
        elif warn_count > 0:
            summary_status = "WARNING"
        else:
            summary_status = "PASS"

        return DiagnosticReport(
            session_id=session_id,
            generated_at=datetime.datetime.now(datetime.timezone.utc).isoformat(),
            total_frames=len(raw_frames),
            duration_seconds=duration,
            summary_status=summary_status,
            pass_count=pass_count,
            warn_count=warn_count,
            fail_count=fail_count,
            info_count=info_count,
            findings=findings,
            metrics=metrics,
        )

