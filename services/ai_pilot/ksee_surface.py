"""Pinned KSEE East Transient 12 ground survey for simulator trials.

Coordinates are extracted from the installed X-Plane 12 Global Airports
apt.dat, not generated by a language model. A different scenery file must be
surveyed anew; this profile refuses to run with changed geometry. The initial
apron connector and the physical hold marking still need visual live review.
"""
from __future__ import annotations

from dataclasses import dataclass
import hashlib
import math
from pathlib import Path

from .ground_guidance import TaxiPoint
from .runway_entry import RunwayEntryGeometry
from .taxi import RoutePurpose, Surface, TaxiLeg, TaxiRoute


APT_SHA256 = "bd7748202a98bf0b134ba38703f98fe606d47c00dc9d447db509845b162ec079"
PARKING_NAME = "East Transient Parking 12"
PARKING_LAT_LON = (32.824456, -116.968545)
TAXI_NODE_IDS = (49, 55, 57, 56, 58, 59, 60, 175, 128, 127, 126, 125, 124)
RUNWAY_ENTRY_NODE = 181
HOLD_NODE = 124
M_PER_DEG_LAT = 111132.92


@dataclass(frozen=True)
class SurfaceSurvey:
    nodes: dict[int, tuple[float, float]]
    edges: dict[frozenset[int], str]
    runway_ends: dict[str, tuple[float, float]]
    runway_width_m: dict[str, float]
    parking_lat_lon: tuple[float, float]

    def local(self, lat_lon: tuple[float, float]) -> TaxiPoint:
        lat0, lon0 = self.parking_lat_lon
        east = (lat_lon[1]-lon0)*111412.84*math.cos(math.radians(lat0))
        north = (lat_lon[0]-lat0)*M_PER_DEG_LAT
        return TaxiPoint(east, north)

    def taxi_route(self) -> tuple[TaxiRoute, dict[str, TaxiPoint]]:
        labels = (PARKING_NAME,) + tuple(f"KSEE node {n}" for n in TAXI_NODE_IDS)
        legs = tuple(TaxiLeg(a, b, Surface.APRON if index == 0 else Surface.TAXIWAY)
                     for index, (a, b) in enumerate(zip(labels, labels[1:])))
        points = {PARKING_NAME: self.local(self.parking_lat_lon)}
        points.update({f"KSEE node {n}": self.local(self.nodes[n]) for n in TAXI_NODE_IDS})
        return TaxiRoute(RoutePurpose.OUTBOUND, legs), points

    def runway_frame(self) -> tuple[float, float, float]:
        """27R heading true, length and entry distance from the east threshold."""
        near = self.runway_ends["27R"]
        far = self.runway_ends["9L"]
        frame = self._frame(near, far)
        along, cross = self._coordinates(frame, self.nodes[RUNWAY_ENTRY_NODE])
        if not 20 <= along <= 150 or abs(cross) > 5:
            raise ValueError("27R entry node is not on the surveyed runway")
        return frame[4], frame[3], along

    def entry_geometry(self) -> RunwayEntryGeometry:
        heading, _length, _entry_along = self.runway_frame()
        center = self.local(self.nodes[RUNWAY_ENTRY_NODE])
        radians = math.radians(heading)
        return RunwayEntryGeometry(
            hold=self.local(self.nodes[HOLD_NODE]),
            centerline_entry=center,
            lineup=TaxiPoint(center.east_m+30*math.sin(radians),
                             center.north_m+30*math.cos(radians)),
            heading_true_deg=heading,
            runway_width_m=self.runway_width_m["27R"],
        )

    def _frame(self, a, b):
        m_lon = 111412.84*math.cos(math.radians(a[0]))
        north = (b[0]-a[0])*M_PER_DEG_LAT
        east = (b[1]-a[1])*m_lon
        length = math.hypot(north, east)
        return (a, north/length, east/length, length,
                math.degrees(math.atan2(east, north)) % 360, m_lon)

    def _coordinates(self, frame, position):
        a, un, ue, _length, _heading, m_lon = frame
        north = (position[0]-a[0])*M_PER_DEG_LAT
        east = (position[1]-a[1])*m_lon
        return (north*un+east*ue, north*-ue+east*un)

    def validate(self) -> None:
        if self.parking_lat_lon != PARKING_LAT_LON:
            raise ValueError("East Transient 12 parking position changed")
        for a, b in zip(TAXI_NODE_IDS, TAXI_NODE_IDS[1:]):
            label = self.edges.get(frozenset((a, b)))
            if label is None or label.startswith("runway"):
                raise ValueError("KSEE taxi route edge missing or crosses a runway")
        if self.edges.get(frozenset((HOLD_NODE, RUNWAY_ENTRY_NODE))) != "taxiway_C D8":
            raise ValueError("D8 runway entry edge changed")
        if self.edges.get(frozenset((RUNWAY_ENTRY_NODE, 89))) != "runway 09L/27R":
            raise ValueError("27R runway graph changed")
        parking = self.local(self.parking_lat_lon)
        first = self.local(self.nodes[TAXI_NODE_IDS[0]])
        if not 20 <= math.hypot(first.east_m-parking.east_m,
                                first.north_m-parking.north_m) <= 50:
            raise ValueError("Parking-to-taxi-network connector changed")
        route_positions = (self.parking_lat_lon,) + tuple(self.nodes[i] for i in TAXI_NODE_IDS)
        for runway_a, runway_b in (("9L", "27R"), ("9R", "27L"), ("17", "35")):
            frame = self._frame(self.runway_ends[runway_a], self.runway_ends[runway_b])
            threshold = self.runway_width_m[runway_a] / 2 + 10
            for start, end in zip(route_positions, route_positions[1:]):
                # Dense geometry audit, separate from planner-proposed surface labels.
                length = math.hypot((end[0]-start[0])*M_PER_DEG_LAT,
                                    (end[1]-start[1])*frame[5])
                for index in range(math.ceil(length)+1):
                    t = min(1., index/max(1, length))
                    point = (start[0]+(end[0]-start[0])*t,
                             start[1]+(end[1]-start[1])*t)
                    along, cross = self._coordinates(frame, point)
                    if 0 <= along <= frame[3] and abs(cross) < threshold:
                        raise ValueError("Taxi route intersects " + runway_a + "/" + runway_b)
        frame = self._frame(self.runway_ends["27R"], self.runway_ends["9L"])
        hold_along, hold_cross = self._coordinates(frame, self.nodes[HOLD_NODE])
        if not 35 <= abs(hold_cross) <= 70 or not 0 <= hold_along <= 150:
            raise ValueError("D8 holding node is not outside 27R edge")
        self.runway_frame()


def read_survey(apt_dat: Path) -> SurfaceSurvey:
    if hashlib.sha256(apt_dat.read_bytes()).hexdigest() != APT_SHA256:
        raise ValueError("Installed Global Airports apt.dat differs from surveyed version")
    nodes: dict[int, tuple[float, float]] = {}
    edges: dict[frozenset[int], str] = {}
    runway_ends: dict[str, tuple[float, float]] = {}
    runway_width_m: dict[str, float] = {}
    parking: tuple[float, float] | None = None
    inside = False
    with apt_dat.open(encoding="utf-8", errors="replace") as stream:
        for line in stream:
            if line.startswith("1 "):
                if inside:
                    break
                inside = " KSEE " in line
            if not inside:
                continue
            parts = line.split()
            if not parts:
                continue
            if parts[0] == "1201" and len(parts) >= 5:
                nodes[int(parts[4])] = (float(parts[1]), float(parts[2]))
            elif parts[0] == "1202" and len(parts) >= 5:
                edges[frozenset((int(parts[1]), int(parts[2])))] = " ".join(parts[4:])
            elif parts[0] == "1300" and PARKING_NAME in line:
                parking = (float(parts[1]), float(parts[2]))
            elif parts[0] == "100":
                runway_ends[parts[8]] = (float(parts[9]), float(parts[10]))
                runway_ends[parts[17]] = (float(parts[18]), float(parts[19]))
                runway_width_m[parts[8]] = runway_width_m[parts[17]] = float(parts[1])
    if parking is None or any(n not in nodes for n in TAXI_NODE_IDS + (RUNWAY_ENTRY_NODE, 89)):
        raise ValueError("Required KSEE parking or taxi nodes missing")
    survey = SurfaceSurvey(nodes, edges, runway_ends, runway_width_m, parking)
    survey.validate()
    return survey
